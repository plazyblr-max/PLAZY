const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.PLAZY_URL || 'http://localhost:8092';

(async () => {
    const browser = await chromium.launch({headless: true, ...(process.env.CHROMIUM_PATH ? {executablePath: process.env.CHROMIUM_PATH} : {})});
    const errors = [];
    const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    const form = page.locator('.pz-wizard');
    const next = () => form.locator('[data-step-next]').click();
    const current = async name => {
        await page.waitForFunction(name => document.querySelector('[data-step="' + name + '"]')?.hidden === false, name);
        assert.equal(await form.locator('.pz-step:visible').count(), 1);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    };
    try {
        await page.goto(base + '/plazy/team/join', {waitUntil: 'networkidle'});
        await page.waitForSelector('.is-guided');
        await current('welcome');
        await next();
        await current('manager');
        await next();
        assert.equal(await form.locator('[data-onboarding-error]').isVisible(), true);
        await page.locator('#pz-manager').fill('Anu Manager');
        await page.locator('#pz-manager').press('Enter');
        await current('mobile');
        await page.locator('#pz-mobile').fill('123');
        await next();
        await current('mobile');
        await page.locator('#pz-mobile').fill('9876543210');
        await next();
        await current('location');
        await page.locator('#pz-locality').fill('Indiranagar');
        await page.locator('#pz-pincode').fill('560038');
        await next();
        await current('security');
        await page.locator('#pz-email').fill('browser-test@example.invalid');
        await page.locator('#pz-password').fill('A-test-password-123');
        await page.locator('#pz-confirm-password').fill('Mismatch-123');
        await next();
        await current('security');
        assert.match(await form.locator('[data-onboarding-error]').textContent(), /do not match/);
        await page.locator('#pz-confirm-password').fill('A-test-password-123');
        await page.locator('[data-onboarding-toggle="pz-password"]').click();
        assert.equal(await page.locator('#pz-password').getAttribute('type'), 'text');
        await next();
        await current('identity');
        await page.locator('#pz-team-name').fill('Bangalore United');
        assert.equal(await page.locator('[data-team-name-preview]').textContent(), 'Bangalore United');
        await next();
        await current('logo');
        await page.locator('#pz-logo').setInputFiles({name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('not an image')});
        await next();
        await current('logo');
        await page.locator('#pz-logo').setInputFiles(__dirname + '/../static/src/img/plazy-touch-icon.png');
        await page.waitForSelector('[data-upload-preview] img');
        await next();
        await current('type');
        await next();
        await current('type');
        await page.locator('input[value="seven_a_side"]').check();
        await next();
        await current('review');
        assert.match(await page.locator('[data-review-details]').textContent(), /7-a-side Football/);
        assert.equal(await page.locator('[data-review-logo] img').count(), 1);
        await page.getByRole('button', {name: 'Edit manager', exact: true}).click();
        await current('manager');
        assert.equal(await page.locator('#pz-manager').inputValue(), 'Anu Manager');
        for (let i = 0; i < 7; i++) await next();
        await current('review');
        // Exercise server validation without sending a real registration email.
        let posted;
        await page.route('**/plazy/team/join', async route => {
            if (route.request().method() !== 'POST') return route.continue();
            posted = route.request().postData();
            await route.fulfill({status: 200, contentType: 'text/html', body: '<p class="pz-server-error">An account already exists for this email address.</p>'});
        });
        await form.locator('[data-step-submit]').click();
        await page.waitForFunction(() => document.querySelector('[data-onboarding-error]').textContent.includes('already exists'));
        assert.match(posted, /name="csrf_token"/);
        assert.match(posted, /seven_a_side/);
        assert.match(posted, /plazy-touch-icon.png/);
        assert.equal(await page.locator('#pz-password').inputValue(), 'A-test-password-123');
        const stored = await page.evaluate(() => sessionStorage.getItem('plazy:onboarding:v1:team'));
        assert.doesNotMatch(stored, /A-test-password|csrf_token|confirm_password/);
        await page.reload({waitUntil: 'networkidle'});
        await page.waitForSelector('.is-guided');
        assert.equal(await page.locator('#pz-team-name').inputValue(), 'Bangalore United');
        assert.equal(await page.locator('#pz-password').inputValue(), '');
        assert.equal(await page.locator('#pz-logo').inputValue(), '');
        assert.equal(await page.locator('.pz-draft-note').isVisible(), true);

        await page.goto(base + '/plazy/player/join', {waitUntil: 'networkidle'});
        await next();
        await page.locator('#pz-player-name').fill('Asha Player');
        await next();
        await current('position');
        await page.locator('input[value="MID"]').check();
        await next();
        await page.locator('#pz-email').fill('asha@example.invalid');
        await next();
        await page.locator('#pz-mobile').fill('9876543210');
        await next();
        await page.locator('#pz-age').fill('24');
        await next();
        await page.locator('#pz-locality').fill('Whitefield');
        await page.locator('#pz-pincode').fill('560066');
        await next();
        await page.locator('#pz-password').fill('Player-password-123');
        await page.locator('#pz-confirm-password').fill('Player-password-123');
        await next();
        await current('review');
        assert.equal(await page.locator('input[name="name"]').inputValue(), 'Asha Player');
        assert.match(await page.locator('[data-review-details]').textContent(), /MID/);
        for (const width of [320, 390, 768, 1440]) {
            await page.setViewportSize({width, height: 900});
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        }
        await page.setViewportSize({width: 390, height: 844});
        await page.screenshot({path: '/tmp/plazy-player-review-mobile.png', fullPage: true});
        await page.getByRole('button', {name: 'Edit position', exact: true}).click();
        await page.screenshot({path: '/tmp/plazy-player-position-mobile.png', fullPage: true});
        await page.emulateMedia({reducedMotion: 'reduce'});
        assert.equal(await page.locator('.pz-step:visible').evaluate(el => getComputedStyle(el).animationName), 'none');
        const noJS = await browser.newContext({javaScriptEnabled: false});
        const fallback = await noJS.newPage();
        await fallback.goto(base + '/plazy/team/join');
        assert.equal(await fallback.locator('.pz-step:visible').count(), 9);
        assert.equal(await fallback.locator('[data-step-submit]').isVisible(), true);
        await noJS.close();
        assert.deepEqual(errors, []);
        console.log('PASS: guided team/player steps, validation, Enter, editing, previews, real POST payload, server errors, recovery, responsive layouts, reduced motion, no-JS fallback.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
